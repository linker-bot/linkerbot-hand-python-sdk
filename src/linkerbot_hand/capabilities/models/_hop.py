"""Shared HOP object capabilities, parameterized by installed joint layout."""

from ...api.commands import AckSupport
from ...api.enums import (
    Confidence,
    HandSide,
    ProtocolKind,
    SampleProjection,
    TransportKind,
)
from ..types import (
    CommandSemantic,
    DeviceCapabilities,
    JointCapability,
    OperationCapabilities,
    StallFieldCapability,
    StallProtectionCapability,
    TelemetrySemantic,
    TransportCapability,
)
from ._common import (
    U8_RANGE,
    angle_command,
    angle_telemetry,
    command,
    identity,
    telemetry,
)

_SENSOR_CHANNELS = ("thumb", "index", "middle", "ring", "pinky")


def shared_capabilities(
    model: str,
    side: HandSide,
    joints: tuple[JointCapability, ...],
    *,
    raw_encoding: str,
    addressing_note: str,
) -> DeviceCapabilities:
    """Declare common HOP objects; model profiles select their extra operations."""
    names = tuple(value.name for value in joints)
    stall_field = StallFieldCapability(
        raw_range=U8_RANGE,
        raw_encoding=raw_encoding,
        raw_unit=None,
        raw_scale_note="only installed public channels are represented",
        unit_confidence=Confidence.UNKNOWN,
    )
    stall = StallProtectionCapability(
        channels=names,
        detection_time=stall_field,
        threshold=stall_field,
        hold_current=stall_field,
        physical_semantics_confidence=Confidence.UNKNOWN,
        safety_range_verified=False,
        read_supported=True,
        write_supported=True,
    )
    return DeviceCapabilities(
        protocol=ProtocolKind.HOP,
        identity=identity(
            model,
            side,
            supported_fields=(
                "serial_number",
                "pcb_version",
                "adapter_board_version",
                "control_board_version",
                "bootloader_version",
                "firmware_version",
                "mechanical_version",
                "product_code",
                "protocol_name",
                "protocol_version",
                "power_supply_range",
                "microcontroller_uid",
                "build_time",
                "supported_interfaces",
                "reported_side",
            ),
        ),
        joints=joints,
        commands=(
            angle_command(
                joints,
                raw_encoding,
                ack_support=AckSupport.SUPPORTED,
                returns_current_state=True,
            ),
            command(
                CommandSemantic.SPEEDS,
                names,
                U8_RANGE,
                raw_encoding,
                raw_unit="count",
                unit_confidence=Confidence.UNKNOWN,
                ack_support=AckSupport.SUPPORTED,
            ),
            command(
                CommandSemantic.ACCELERATIONS,
                names,
                U8_RANGE,
                raw_encoding,
                raw_unit="count",
                unit_confidence=Confidence.UNKNOWN,
                ack_support=AckSupport.SUPPORTED,
            ),
            command(
                CommandSemantic.TORQUES_LIMITS,
                names,
                U8_RANGE,
                raw_encoding,
                raw_unit=None,
                unit_confidence=Confidence.UNKNOWN,
                ack_support=AckSupport.SUPPORTED,
            ),
            command(
                CommandSemantic.CURRENT_LIMITS,
                names,
                U8_RANGE,
                raw_encoding,
                raw_unit="count",
                unit_confidence=Confidence.UNKNOWN,
                ack_support=AckSupport.SUPPORTED,
            ),
            command(
                CommandSemantic.MOTION_TIMES,
                names,
                U8_RANGE,
                raw_encoding,
                raw_unit="count",
                raw_scale_note="documentation states 10 ms/count; API returns count",
                unit_confidence=Confidence.DOCUMENTED,
                ack_support=AckSupport.SUPPORTED,
            ),
            command(
                CommandSemantic.STALL_DETECTION_TIMES,
                names,
                U8_RANGE,
                raw_encoding,
                raw_unit=None,
                unit_confidence=Confidence.UNKNOWN,
                ack_support=AckSupport.SUPPORTED,
            ),
            command(
                CommandSemantic.STALL_THRESHOLDS,
                names,
                U8_RANGE,
                raw_encoding,
                raw_unit=None,
                unit_confidence=Confidence.UNKNOWN,
                ack_support=AckSupport.SUPPORTED,
            ),
            command(
                CommandSemantic.STALL_HOLD_CURRENTS,
                names,
                U8_RANGE,
                raw_encoding,
                raw_unit=None,
                unit_confidence=Confidence.UNKNOWN,
                ack_support=AckSupport.SUPPORTED,
            ),
        ),
        telemetry=(
            angle_telemetry(
                joints,
                raw_encoding,
                recommended_hz=30,
                estimated_transaction_s=0.004,
            ),
            telemetry(
                TelemetrySemantic.MEASURED_SPEEDS,
                names,
                raw_encoding,
                shape=(len(joints),),
                raw_range=U8_RANGE,
                raw_unit="count",
                unit_confidence=Confidence.UNKNOWN,
                recommended_hz=30,
                stale_after_s=0.1,
                estimated_transaction_s=0.004,
            ),
            telemetry(
                TelemetrySemantic.CONFIGURED_SPEEDS,
                names,
                raw_encoding,
                shape=(len(joints),),
                raw_range=U8_RANGE,
                raw_unit="count",
                unit_confidence=Confidence.UNKNOWN,
                recommended_hz=30,
                stale_after_s=0.1,
                estimated_transaction_s=0.004,
                device_measured=False,
            ),
            telemetry(
                TelemetrySemantic.CONFIGURED_ACCELERATIONS,
                names,
                raw_encoding,
                shape=(len(joints),),
                raw_range=U8_RANGE,
                raw_unit="count",
                unit_confidence=Confidence.UNKNOWN,
                recommended_hz=10,
                stale_after_s=0.3,
                estimated_transaction_s=0.004,
                device_measured=False,
            ),
            telemetry(
                TelemetrySemantic.TORQUES_LIMITS,
                names,
                raw_encoding,
                shape=(len(joints),),
                raw_range=U8_RANGE,
                raw_unit=None,
                unit_confidence=Confidence.UNKNOWN,
                recommended_hz=30,
                stale_after_s=0.1,
                estimated_transaction_s=0.004,
                device_measured=False,
            ),
            telemetry(
                TelemetrySemantic.TEMPERATURES,
                names,
                raw_encoding,
                shape=(len(joints),),
                raw_range=U8_RANGE,
                raw_unit="count",
                unit_confidence=Confidence.UNKNOWN,
                recommended_hz=1,
                stale_after_s=3,
                estimated_transaction_s=0.004,
            ),
            telemetry(
                TelemetrySemantic.FORCE,
                _SENSOR_CHANNELS,
                "o30_tactile_descriptor",
                shape=(5,),
                raw_range=None,
                raw_unit=None,
                raw_scale_note=(
                    "runtime metadata supplies sensor type, unit, shape, descriptor, "
                    "and exact raw byte stream; no physical conversion"
                ),
                unit_confidence=Confidence.DOCUMENTED,
                recommended_hz=10,
                stale_after_s=0.3,
                estimated_transaction_s=0.2,
                payload_projection=SampleProjection.TACTILE_DESCRIPTOR,
            ),
            telemetry(
                TelemetrySemantic.CURRENTS,
                names,
                raw_encoding,
                shape=(len(joints),),
                raw_range=U8_RANGE,
                raw_unit="count",
                unit_confidence=Confidence.UNKNOWN,
                recommended_hz=10,
                stale_after_s=0.3,
                estimated_transaction_s=0.004,
            ),
            telemetry(
                TelemetrySemantic.CURRENT_LIMITS,
                names,
                raw_encoding,
                shape=(len(joints),),
                raw_range=U8_RANGE,
                raw_unit="count",
                unit_confidence=Confidence.UNKNOWN,
                recommended_hz=30,
                stale_after_s=0.1,
                estimated_transaction_s=0.004,
                device_measured=False,
            ),
            telemetry(
                TelemetrySemantic.TORQUES,
                names,
                raw_encoding,
                shape=(len(joints),),
                raw_range=U8_RANGE,
                raw_unit=None,
                unit_confidence=Confidence.UNKNOWN,
                recommended_hz=10,
                stale_after_s=0.3,
                estimated_transaction_s=0.004,
            ),
            telemetry(
                TelemetrySemantic.FAULTS,
                names,
                "u8_bitmask_v25_object",
                shape=(len(joints),),
                raw_range=U8_RANGE,
                raw_unit=None,
                unit_confidence=Confidence.DOCUMENTED,
                recommended_hz=5,
                stale_after_s=0.5,
                estimated_transaction_s=0.004,
                # ``protocols/o30/telemetry.py`` wires decode_fault_statuses for
                # this object, so every fault sample carries per-joint
                # JointFaultStatus values next to the raw bytes.
                decoded_statuses=True,
            ),
            telemetry(
                TelemetrySemantic.VOLTAGES,
                names,
                raw_encoding,
                shape=(len(joints),),
                raw_range=U8_RANGE,
                raw_unit="count",
                unit_confidence=Confidence.UNKNOWN,
                recommended_hz=1,
                stale_after_s=3,
                estimated_transaction_s=0.004,
            ),
            telemetry(
                TelemetrySemantic.MOTION_TIMES,
                names,
                raw_encoding,
                shape=(len(joints),),
                raw_range=U8_RANGE,
                raw_unit="count",
                raw_scale_note="documentation states 10 ms/count; API returns count",
                unit_confidence=Confidence.DOCUMENTED,
                recommended_hz=10,
                stale_after_s=0.3,
                estimated_transaction_s=0.004,
                device_measured=False,
            ),
            *(
                telemetry(
                    semantic,
                    names,
                    raw_encoding,
                    shape=(len(joints),),
                    raw_range=U8_RANGE,
                    raw_unit=None,
                    unit_confidence=Confidence.UNKNOWN,
                    recommended_hz=1,
                    stale_after_s=3,
                    estimated_transaction_s=0.004,
                    device_measured=False,
                )
                for semantic in (
                    TelemetrySemantic.STALL_DETECTION_TIMES,
                    TelemetrySemantic.STALL_THRESHOLDS,
                    TelemetrySemantic.STALL_HOLD_CURRENTS,
                )
            ),
        ),
        stall_protection=stall,
        transport=TransportCapability(
            kind=TransportKind.CAN_FD,
            nominal_bitrate=1_000_000,
            # BRS is disabled, so the data phase always runs at the 1 Mbit
            # nominal rate and the interface's configured data bitrate is
            # irrelevant. Leaving it unconstrained lets any dbitrate (1M/5M/7M…)
            # connect and be discovered.
            data_bitrate=None,
            addressing_note=addressing_note,
        ),
        operations=OperationCapabilities(
            read_stall_protection=True,
            write_stall_protection=True,
        ),
    )
